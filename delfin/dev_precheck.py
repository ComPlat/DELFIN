"""``delfin-dev precheck``: run CI's project-wide pins locally.

A pull request can pass its own tests and still fail CI on a pin that
lives elsewhere in the tree. This module maps the files a branch changed
(from ``git diff --name-only origin/main...HEAD``) to the pin test files
that guard them, plus two always-on checks:

- ruff with the gated selection CI enforces (F821,F811,F601,F402,F823),
- the TUI protocol regeneration, done in Python directly from
  ``python -m delfin.agent.service.protocol`` so bun is not needed.
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]

#: Files the TUI protocol pin watches. When one changes, precheck
#: regenerates the TypeScript from the Python definition and compares.
PROTOCOL_PIN = "tui/test/protocol/generated.test.ts"

#: One table: a changed path pattern (fnmatch) -> the pin test files that
#: guard what it controls. A change in a listed path runs these pins even
#: though the PR's own tests pass.
PIN_MAP: list[tuple[str, set[str]]] = [
    # A tool schema lives next to the dispatch that runs it; both the
    # executor-dispatch pin and the tool-surface registry read
    # delfin/agent/api_client.py.
    ("delfin/agent/api_client.py", {
        "tests/test_a_tool_reaches_the_function_behind_it.py",
        "tests/test_the_tool_surface_is_exercised.py",
    }),
    # The dashboard's tool catalogue feeds the same registry.
    ("delfin/api.py", {
        "tests/test_the_tool_surface_is_exercised.py",
    }),
    # pyproject's entry points and the console-script modules the bash
    # gate must ask for; both pins read [project.scripts].
    ("pyproject.toml", {
        "tests/test_functional_contracts.py",
        "tests/test_an_acting_delfin_command_is_asked.py",
    }),
    # The wire protocol between the TUI and the agent service.
    ("delfin/agent/service/protocol.py", {PROTOCOL_PIN}),
    # The agent writes user state with a sanitized child environment.
    ("delfin/agent/terminal_confirm.py",
     {"tests/test_a_child_process_writes_into_no_real_home.py"}),
    # The licence tables REUSE reads, and the guard that keeps ORCA
    # output out of the tree.
    ("REUSE.toml", {
        "tests/test_every_file_has_a_licence_by_reuse.py",
        "tests/test_license_guard.py",
    }),
    ("LICENSES/*", {
        "tests/test_every_file_has_a_licence_by_reuse.py",
        "tests/test_license_guard.py",
    }),
    ("LICENSE_GUARD.md", {"tests/test_license_guard.py"}),
    # The launcher package and the checksums CI verifies.
    ("tools/windows-launcher/*",
     {"tests/test_windows_launcher.py"}),
]

RUFF_SELECT = ["F821", "F811", "F601", "F402", "F823"]


def changed_files(rev_range: str = "origin/main...HEAD",
                  repo: Path = REPO) -> list[str]:
    """Files the branch changed, as ``git diff --name-only`` lists them."""
    out = subprocess.run(
        ["git", "diff", "--name-only", rev_range],
        cwd=repo, capture_output=True, text=True,
    )
    if out.returncode != 0:
        raise SystemExit(
            f"git diff {rev_range} failed: {out.stderr.strip()}"
        )
    return [line for line in out.stdout.splitlines() if line]


def select_pins(changed: list[str]) -> set[str]:
    """Union of the pin test files guarding the changed paths."""
    import fnmatch

    pins: set[str] = set()
    for path in changed:
        if path.startswith("tests/") and path.endswith(".py"):
            pins.add(path)
        for pattern, guarded in PIN_MAP:
            if fnmatch.fnmatch(path, pattern):
                pins |= guarded
    return pins


# ---------------------------------------------------------------------------
# The TypeScript protocol generator, in Python.
#
# Identical to tui/scripts/gen-protocol.ts: same tsType/fields/map rules,
# same header lines, same order of parts. A test compares its output with
# the committed tui/src/protocol/generated.ts, so the two cannot drift.

HEADER = [
    "// Generated by tui/scripts/gen-protocol.ts from delfin/agent/service/protocol.py.",
    "// Do not edit: run `bun scripts/gen-protocol.ts` after changing the Python side.",
    "",
]


def _ts_type(schema: dict) -> str:
    if "const" in schema:
        return json.dumps(schema["const"])
    kind = schema.get("type")
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "object":
        return "Record<string, unknown>"
    if kind == "array":
        return _ts_type(schema.get("items") or {}) + "[]"
    return "unknown"


def _fields(schema: dict, indent: str = "  ") -> str:
    required = set(schema.get("required") or [])
    lines = []
    for name, field in (schema.get("properties") or {}).items():
        if name in required:
            lines.append(f'{indent}{json.dumps(name)}: {_ts_type(field)}')
        else:
            # An optional field may also come as null: Python sends None
            # for one it has no value for (a session's title).
            lines.append(
                f'{indent}{json.dumps(name)}?: {_ts_type(field)} | null'
            )
    return "\n".join(lines)


def _type_name(dotted: str, suffix: str) -> str:
    words = dotted.replace("-", "_").replace(".", "_").split("_")
    return "".join(w[:1].upper() + w[1:] for w in words) + suffix


def _map(name: str, entries: dict, suffix: str) -> list[str]:
    out = []
    for key, schema in entries.items():
        body = _fields(schema)
        interface = f"export interface {_type_name(key, suffix)} {{"
        out.append(f"{interface}\n{body}\n}}" if body
                   else f"export interface {_type_name(key, suffix)} {{}}")
    inner = "\n".join(
        f'  {json.dumps(key)}: {_type_name(key, suffix)}'
        for key in entries
    )
    out.append(f"export interface {name} {{\n{inner}\n}}")
    return out


def generate_protocol_text(schema: dict) -> str:
    """The content of tui/src/protocol/generated.ts, from the schema."""
    errors = sorted(schema["errors"].items(), key=lambda kv: kv[1],
                    reverse=True)
    parts = [
        *HEADER,
        f'export const PROTOCOL_VERSION = {int(schema["protocolVersion"])}',
        "",
        f'export const DURABLE_EVENTS: ReadonlySet<string> = new Set('
        f'{json.dumps(schema["durableEvents"], separators=(",", ":"))})',
        "",
        "export const ERRORS = {",
        *[f"  {name}: {code}," for name, code in errors],
        "} as const",
        "",
        *_map("WorkerRequests", schema["requests"], "Params"),
        *_map("WorkerResults", schema["results"], "Result"),
        *_map("WorkerEvents", schema["events"], "Event"),
        *_map("ServiceRequests", schema["service"]["requests"], "Params"),
        *_map("ServiceResults", schema["service"]["results"], "Result"),
        *_map("ServiceEvents", schema["service"]["events"], "Event"),
        "export interface SessionSummary {\n"
        f'{_fields(schema["service"]["sessionSummary"])}\n}}',
        "",
        "export interface AttentionItem {\n"
        f'{_fields(schema["service"]["attentionItem"])}\n}}',
        "",
        "/** Every event a window can receive: a session's own, and the "
        "service's. */",
        "export type AnyEvent = WorkerEvents[keyof WorkerEvents] | "
        "ServiceEvents[keyof ServiceEvents]",
        "",
        "/** Requests a window sends: the service's, and a session's "
        "(with sessionId). */",
        "export type Requests = ServiceRequests & {",
        "  [M in keyof WorkerRequests]: WorkerRequests[M] & "
        "{ sessionId: string }",
        "}",
        "export type Results = ServiceResults & WorkerResults",
        "",
    ]
    return "\n".join(parts)


def load_protocol_schema(python_exe: str | None = None) -> dict:
    """Run ``python -m delfin.agent.service.protocol`` and parse the JSON."""
    exe = python_exe or sys.executable
    run = subprocess.run(
        [exe, "-m", "delfin.agent.service.protocol"],
        cwd=REPO, capture_output=True, text=True,
    )
    if run.returncode != 0:
        raise SystemExit(run.stderr.strip())
    return json.loads(run.stdout)


# ---------------------------------------------------------------------------
# The precheck command itself.


def precheck(argv: list[str]) -> int:
    """Run changed test files, the pins they guard, ruff, and the
    protocol regeneration check. Exit non-zero on any failure."""
    import argparse

    parser = argparse.ArgumentParser(
        prog="delfin-dev precheck",
        description="Run the project-wide pins a PR would trip in CI.",
    )
    parser.add_argument(
        "--diff", default="origin/main...HEAD",
        help="git revision range to diff (default origin/main...HEAD)",
    )
    parser.add_argument(
        "--python", default=None,
        help="interpreter for the pytest runs (default sys.executable)",
    )
    parser.add_argument(
        "--skip-ruff", action="store_true",
        help="skip the ruff gated-selection check",
    )
    args = parser.parse_args(argv)

    changed = changed_files(args.diff)
    pins = select_pins(changed)
    print(f"changed files: {len(changed)}; pin test files: {len(pins)}")

    failures: list[str] = []

    if pins:
        pytest = [args.python or sys.executable, "-m", "pytest", "-q",
                  *sorted(pins)]
        print("$", " ".join(pytest))
        run = subprocess.run(pytest, cwd=REPO)
        if run.returncode != 0:
            failures.append("pytest pins")

    if not args.skip_ruff:
        ruff = [sys.executable, "-m", "ruff", "check", "delfin/", "tests/",
                "--select", ",".join(RUFF_SELECT),
                "--output-format", "github"]
        print("$", " ".join(ruff))
        run = subprocess.run(ruff, cwd=REPO, capture_output=True, text=True)
        sys.stdout.write(run.stdout)
        sys.stderr.write(run.stderr)
        if run.returncode != 0:
            failures.append("ruff gated selection")

    protocol_paths = [p for p in changed
                      if p == "delfin/agent/service/protocol.py"]
    if protocol_paths:
        schema = load_protocol_schema()
        text = generate_protocol_text(schema)
        committed = (REPO / "tui" / "src" / "protocol" / "generated.ts"
                     ).read_text(encoding="utf-8")
        if text == committed:
            print("tui/src/protocol/generated.ts matches the Python "
                  "definition")
        else:
            print("tui/src/protocol/generated.ts is stale: regenerate "
                  "with delfin-dev precheck --write-protocol",
                  file=sys.stderr)
            failures.append("TUI protocol regeneration")

    if failures:
        print("precheck FAILED: " + "; ".join(failures))
        return 1
    print("precheck OK")
    return 0
