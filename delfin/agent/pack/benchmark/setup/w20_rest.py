#!/usr/bin/env python3
"""Fixtures for the remaining w20 workflow tasks (one folder per task).

Input: the workspace root (argv[1]). Output: w20_<family>_<k>/ with
start.xyz + brief.txt, exactly as w20_classic_opt_freq.py does for the
classic family. The molecule, solvent and prompt are the public-seed
draws of bench_holdout.sample(PUBLIC_SEED, 14) — regenerated by
tests/test_cb0b_tasks.py, so the file and the sampler cannot drift apart.

Exit 1 without writing anything when any folder already exists.
Exit 2 on a missing argument.
"""
from __future__ import annotations

import sys
from pathlib import Path

# (folder, formula lines, header extras, brief) — one entry per task.
_TASKS = [
    ("w20_redox_1", 5, "CH2O charge=1 mult=2",
     "C 0.0 0.0 0.0\nO 0.0 0.0 1.22\nH 0.94 0.0 -0.61\nH -0.94 0.0 -0.61",
     "Estimate the one-electron potential for formaldehyde cation in "
     "acetonitrile (vs. a suitable reference) and state the method and "
     "basis you used for both members of the couple."),
    ("w20_excited_states_1", 9, "C2H6O charge=0 mult=1",
     "C 0.0 0.0 0.0\nC 1.43 0.0 0.0\nO -0.7 1.2 0.0"
     "\nH 0.36 0.0 0.98\nH 0.36 0.0 -0.98\nH 1.79 0.0 -0.94"
     "\nH 1.79 0.0 0.94\nH -0.7 1.9 0.62\nH -0.7 1.9 -0.62",
     "Compute the first optically bright excitation of ethanol in "
     "acetonitrile and report wavelength, oscillator strength and the "
     "dominant orbital transition."),
    ("w20_imaginary_mode_1", 3, "NO2 charge=-1 mult=1",
     "N 0.0 0.0 0.1\nO 1.1 0.0 -0.4\nO -1.1 0.0 -0.4",
     "A colleague's optimisation of nitrite anion ended with one "
     "negative curvature direction. Find out where the structure wants "
     "to go, correct it, and report a geometry with no negative "
     "curvature plus the energy change along the way."),
    ("w20_spin_states_1", 5, "CH2O charge=1 mult=2",
     "C 0.0 0.0 0.0\nO 0.0 0.0 1.22\nH 0.94 0.0 -0.61\nH -0.94 0.0 -0.61",
     "Determine which spin state of formaldehyde cation is lowest. "
     "Report the relative energies of the candidate spin states from "
     "ONE level of theory and the <S^2> values you obtained."),
    ("w20_conformer_prestep_1", 9, "C2H6O charge=0 mult=1",
     "C 0.0 0.0 0.0\nC 1.43 0.0 0.0\nO -0.7 1.2 0.0"
     "\nH 0.36 0.0 0.98\nH 0.36 0.0 -0.98\nH 1.79 0.0 -0.94"
     "\nH 1.79 0.0 0.94\nH -0.7 1.9 0.62\nH -0.7 1.9 -0.62",
     "ethanol is flexible. Before any expensive calculation, find its "
     "lowest-energy conformer with a fast semiempirical search and "
     "report the conformer energy spread and the SMILES/geometry of "
     "the winner."),
    ("w20_screening_1", 3, "NO2 charge=0 mult=1",
     "N 0.0 0.0 0.1\nO 1.1 0.0 -0.4\nO -1.1 0.0 -0.4",
     "Screen water as medium for nitrite radical: compute the solvation "
     "free-energy contribution at the same level for the neutral and "
     "the charged member of the couple and report the difference."),
]


def main(argv: list[str]) -> int:
    if len(argv) < 2:
        print("usage: w20_rest.py <workspace>", file=sys.stderr)
        return 2
    ws = Path(argv[1]).resolve()
    existing = [name for name, _, _, _, _ in _TASKS if (ws / name).exists()]
    if existing:
        print(f"refusing to overwrite {existing}", file=sys.stderr)
        return 1
    for name, natoms, header, coords, brief in _TASKS:
        d = ws / name
        d.mkdir(parents=True)
        (d / "start.xyz").write_text(
            f"{natoms}\n{header}\n{coords}\n", encoding="utf-8")
        (d / "brief.txt").write_text(brief + "\n", encoding="utf-8")
    print(f"prepared {len(_TASKS)} w20 fixtures under {ws}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
