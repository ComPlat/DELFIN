def render_entry(e: Entry) -> str:
    lines = ["---", f"title: {e.title}", f"topic: {e.topic}",
             f"scope: {e.scope}"]
    lines += [f"provenance: {p.render()}" for p in e.provenance]
    lines += [f"review_by: {e.review_by}", "---",
              f"Situation: {e.situation.strip()}",
              f"Lesson: {e.lesson.strip()}",
              f"Why: {e.why.strip()}"]
    if e.extra.strip():
        lines += ["", e.extra.strip()]
    return "\n".join(lines) + "\n"


_LABELS = ("situation", "lesson", "why")


def parse_entry(text: str, *, slug: str = "", path: Optional[Path] = None,
                layer: str = GLOBAL) -> Entry:
    """Parse one entry. Malformed parts become empty fields, which the
    template check names; parsing itself never raises on content."""
    text = str(text or "")
    meta: dict = {}
    prov: list = []
    body = text
    if text.startswith("---\n"):
        end = text.find("\n---", 4)
        if end > 0:
            block, body = text[4:end], text[end + 4:].lstrip("\n")
            for line in block.splitlines():
                key, sep, value = line.partition(":")
                if not sep:
                    continue
                key, value = key.strip().lower(), value.strip()
                if key == "provenance":
                    parts = [p.strip() for p in value.split("|")]
                    parts += [""] * (3 - len(parts))
                    prov.append(Provenance(*parts[:3]))
                else:
                    meta[key] = value
    fields = {k: [] for k in _LABELS}
    extra: list = []
    current = None
    for line in body.splitlines():
        m = re.match(r"^(Situation|Lesson|Why):\s*(.*)$", line)
        if m:
            current = m.group(1).lower()
            fields[current].append(m.group(2))
        elif current and line.strip():
            fields[current].append(line.strip())
        elif not line.strip():
            current = None if current and fields[current] else current
        else:
            extra.append(line)
    return Entry(
        slug=slug or (path.stem if path else ""),
        title=meta.get("title", ""), topic=meta.get("topic", ""),
        scope=meta.get("scope", ""), provenance=prov,
        review_by=meta.get("review_by", ""),
        situation=" ".join(fields["situation"]).strip(),
        lesson=" ".join(fields["lesson"]).strip(),
        why=" ".join(fields["why"]).strip(),
        path=path, layer=layer, extra="\n".join(extra).strip())


def read_entries(folder: Path | str, *, layer: str = GLOBAL) -> list[Entry]:
    d = Path(folder)
    if not d.is_dir():
        return []
    out = []
    for p in sorted(d.glob("*.md")):
        if p.name in _RESERVED or p.is_symlink():
            continue
        try:
            # A link out of the folder is not this folder's knowledge.
            p.resolve().relative_to(d.resolve())
            with open(p, encoding="utf-8", errors="replace") as fh:
                raw = fh.read(16_000)
        except (OSError, ValueError):
            continue
        out.append(parse_entry(raw, slug=p.stem, path=p, layer=layer))
    return out


def write_entry(folder: Path | str, e: Entry) -> Path:
    d = Path(folder)
    d.mkdir(parents=True, exist_ok=True)
    p = d / f"{e.slug}.md"
    p.write_text(render_entry(e), encoding="utf-8")
    return p


