def _cell(s: str) -> str:
    return str(s or "").replace("|", "/").replace("\n", " ").strip()


def render_index(folder: Path | str) -> str:
    entries = read_entries(folder)
    lines = [_INDEX_HEADER, "", "# Knowledge index", ""]
    for topic in sorted({e.topic for e in entries}):
        lines += [f"## {topic}", "",
                  "| entry | scope | provenance | review by |",
                  "|---|---|---|---|"]
        for e in sorted((x for x in entries if x.topic == topic),
                        key=lambda x: x.slug):
            prov = "; ".join(f"{p.author} {p.date}" for p in e.provenance)
            lines.append(f"| [{_cell(e.title)}]({e.slug}.md) | {e.scope} | "
                         f"{_cell(prov)} | {e.review_by} |")
        lines.append("")
    if not entries:
        lines.append("(no entries yet)")
        lines.append("")
    return "\n".join(lines)


def write_index(folder: Path | str) -> Path:
    p = Path(folder) / INDEX_FILE
    p.write_text(render_index(folder), encoding="utf-8")
    return p


def index_in_sync(folder: Path | str) -> bool:
    p = Path(folder) / INDEX_FILE
    try:
        return p.read_text(encoding="utf-8") == render_index(folder)
    except OSError:
        return False


