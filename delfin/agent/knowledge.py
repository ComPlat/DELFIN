def _norm(s: str) -> str:
    from .memory_store import _normalise_text
    return re.sub(r"\W+", " ", _normalise_text(s)).strip()


def _shingles(s: str, k: int = 3) -> set:
    words = _norm(s).split()
    return {" ".join(words[i:i + k]) for i in range(max(0, len(words) - k + 1))}


def _shingle_jaccard(a: str, b: str) -> float:
    sa, sb = _shingles(a), _shingles(b)
    if not sa or not sb:
        return 0.0
    return len(sa & sb) / len(sa | sb)


def _sims(a: Entry, b: Entry) -> tuple[float, float, float]:
    from .memory_store import _jaccard
    body_a = f"{a.title} {a.situation} {a.lesson}"
    body_b = f"{b.title} {b.situation} {b.lesson}"
    return (_jaccard(a.situation, b.situation), _jaccard(body_a, body_b),
            _shingle_jaccard(body_a, body_b))


def near_duplicate(a: Entry, b: Entry) -> bool:
    """Same lesson: same normalised title, or similar text with the same
    polarity words."""
    from .memory_store import _inverts_polarity
    if a.slug == b.slug and a.path == b.path:
        return False
    if _inverts_polarity(a.lesson, b.lesson):
        return False
    if _norm(a.title) and _norm(a.title) == _norm(b.title):
        return True
    sit, body, sh = _sims(a, b)
    return body >= 0.55 or sh >= 0.5 or (sit >= 0.8 and body >= 0.45)


def contradicts(a: Entry, b: Entry) -> bool:
    """Same situation, opposite advice: polarity words differ."""
    from .memory_store import _inverts_polarity
    if not _inverts_polarity(a.lesson, b.lesson):
        return False
    sit, body, _sh = _sims(a, b)
    return sit >= 0.6 or body >= 0.5


def merge_entries(into: Entry, other: Entry, *, text_from: Optional[Entry]
                  = None) -> Entry:
    """``into`` with ``other``'s provenance added and the later review
    date. The wording is ``text_from``'s (default ``into``)."""
    src = text_from or into
    prov = list(into.provenance)
    for p in other.provenance:
        if p not in prov:
            prov.append(p)
    return replace(into, provenance=prov,
                   review_by=max(into.review_by, other.review_by),
                   title=src.title, situation=src.situation,
                   lesson=src.lesson, why=src.why)


