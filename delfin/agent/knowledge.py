def global_dir() -> Path:
    return Path(__file__).resolve().parent / "pack" / "knowledge"


def project_dir(repo_root: Path | str) -> Path:
    return Path(repo_root) / ".delfin" / "knowledge"


def is_delfin_repo(path: Path | str | None) -> bool:
    """Whether ``path`` lies in a checkout of the DELFIN code itself."""
    if not path:
        return False
    try:
        cur = Path(path).resolve()
    except OSError:
        return False
    for d in (cur, *cur.parents):
        if (d / "delfin" / "agent" / "pack" / "manifest.yaml").is_file():
            return True
    return False


def repo_root_of(path: Path | str) -> Path:
    try:
        from .memory_store import _repository_root
        return Path(_repository_root(Path(path)))
    except Exception:
        return Path(path)


def slugify(title: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", (title or "").lower()).strip("-")
    return (s[:60].rstrip("-") or "lesson")


def valid_evidence(pointer: str) -> bool:
    return bool(_EVIDENCE_RE.match(str(pointer or "").strip()))


