def read_topics(folder: Path | str | None = None) -> dict:
    """``{slug: description}`` from ``TOPICS.md`` (lines ``- slug: text``)."""
    p = Path(folder or global_dir()) / TOPICS_FILE
    topics: dict = {}
    try:
        for line in p.read_text(encoding="utf-8").splitlines():
            m = re.match(r"^-\s+([a-z0-9-]+):?\s*(.*)$", line.strip())
            if m:
                topics[m.group(1)] = m.group(2).strip()
    except OSError:
        pass
    return topics


def write_topics(folder: Path | str, topics: dict) -> Path:
    p = Path(folder) / TOPICS_FILE
    p.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# Knowledge topics", "",
             "The fixed taxonomy of `delfin/agent/pack/knowledge/`. Only a "
             "knowledge admin adds a topic.", ""]
    lines += [f"- {k}: {v}".rstrip(": ").rstrip() if not v else f"- {k}: {v}"
              for k, v in topics.items()]
    p.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return p


