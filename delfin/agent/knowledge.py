def template_findings(e: Entry, *, topics: Optional[dict] = None,
                      layer: Optional[str] = None) -> list[str]:
    """What breaks the one-lesson template; empty when it holds."""
    layer = layer or e.layer
    out: list[str] = []
    if not e.title.strip() or "\n" in e.title or len(e.title) > MAX_TITLE:
        out.append(f"title: one line of 1-{MAX_TITLE} characters")
    if not _SLUG_RE.match(e.slug or ""):
        out.append("slug: lower-case letters, digits and '-'")
    if layer == GLOBAL:
        known = topics if topics is not None else read_topics()
        if e.topic not in known:
            out.append(f"topic: {e.topic!r} is not in the taxonomy "
                       f"({', '.join(sorted(known)) or 'none'}); only an "
                       "admin adds a topic")
    elif not _SLUG_RE.match(e.topic or ""):
        out.append("topic: a slug")
    if e.scope not in SCOPES.get(layer, ()):
        out.append(f"scope: one of {', '.join(SCOPES.get(layer, ()))}")
    if not e.provenance:
        out.append("provenance: at least one 'author | date | evidence'")
    for p in e.provenance:
        if not p.author or not _SLUG_RE.match(p.author.lower()):
            out.append(f"provenance: author handle {p.author!r} invalid")
        if not _DATE_RE.match(p.date or ""):
            out.append(f"provenance: date {p.date!r} is not YYYY-MM-DD")
        if not valid_evidence(p.evidence):
            out.append(f"provenance: evidence {p.evidence[:40]!r} is not a "
                       "pointer (kind:ref, e.g. test:tests/x.py::t); raw "
                       "transcripts are never evidence")
    try:
        dt.date.fromisoformat(e.review_by)
    except ValueError:
        out.append("review_by: a YYYY-MM-DD date")
    for label in _LABELS:
        if not getattr(e, label).strip():
            out.append(f"{label}: missing")
    if e.words > MAX_WORDS:
        out.append(f"length: {e.words} words > {MAX_WORDS}; longer material "
                   "belongs in a skill or the docs")
    if e.extra.strip():
        out.append("body: text outside Situation/Lesson/Why (one lesson per "
                   "entry)")
    return out


