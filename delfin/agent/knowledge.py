"""Repository knowledge: lessons shared through git, read as data.

Layers (the personal and swarm layers live elsewhere and never reach a
repository: ``knowledge_private``, ``swarm_memory``):

* GLOBAL -- ``delfin/agent/pack/knowledge/*.md`` in the DELFIN repository,
  reaching every user after ``git pull``. ``scope: always`` loads in any
  workspace, ``scope: delfin-development`` only when the workspace is the
  DELFIN code itself.
* PROJECT -- ``<repository>/.delfin/knowledge/*.md`` in any other
  repository, ``scope: project``. Inside the DELFIN tree there is only the
  global layer (one public repository, one layer).

Entry template, one lesson per file (``render_entry``/``parse_entry``)::

    ---
    title: <one line>
    topic: <a slug from TOPICS.md>
    scope: always | delfin-development | project
    provenance: <author handle> | <YYYY-MM-DD> | <kind:pointer>
    review_by: <YYYY-MM-DD>
    ---
    Situation: <when it applies>
    Lesson: <what to do>
    Why: <the reason; the evidence pointer is in provenance>

``provenance`` may repeat (a merge keeps every author). Situation, Lesson
and Why together are at most :data:`MAX_WORDS` words: longer material
belongs in a skill or in the docs. The topic must be in the taxonomy
(``TOPICS.md``); only an admin adds a topic (``knowledge_curation``).
``INDEX.md`` is generated from the entries and never edited by hand.

Read path (:func:`load_block`): entries are ranked against the task by
``memory_store.bm25_scores`` and only matching ones are injected, inside
``max_chars``; expired entries (``review_by`` before today) are not loaded
until re-reviewed; an entry whose text carries an instruction about
permissions, checks or protected files (``knowledge_check.
instruction_findings``) is refused at load time too; the block is fenced
with ``untrusted.wrap`` and a nonce from ``project_memory._fence_nonce``
(stable for the prompt cache, unknowable to the entry's author). Load
counts go to a local usage file (``~/.delfin/knowledge/usage.json``) and
never leave the machine.

Similarity (``near_duplicate``/``contradicts``): ``memory_store._jaccard``
over normalised tokens plus word-3-shingle Jaccard and same-title; a pair
that is similar but differs in its polarity words
(``memory_store._inverts_polarity``) is a contradiction, not a duplicate.
Rejected: embeddings (a model and a network for a lint that must run in
CI on every machine).
"""
from __future__ import annotations

import datetime as dt
import json
import re
import time
from dataclasses import dataclass, field, replace
from pathlib import Path
from typing import Iterable, Optional

__all__ = [
    "Entry", "Provenance", "GLOBAL", "PROJECT", "DEFAULT_TOPICS",
    "global_dir", "project_dir", "render_entry", "parse_entry",
    "read_entries", "write_entry", "read_topics", "write_topics",
    "template_findings", "render_index", "write_index", "index_in_sync",
    "near_duplicate", "contradicts", "merge_entries", "load_block",
    "read_usage", "is_delfin_repo", "valid_evidence", "slugify",
]

GLOBAL = "global"
PROJECT = "project"
SCOPES = {GLOBAL: ("always", "delfin-development"), PROJECT: ("project",)}
MAX_WORDS = 150
MAX_TITLE = 100
INDEX_FILE = "INDEX.md"
TOPICS_FILE = "TOPICS.md"
_RESERVED = {INDEX_FILE, TOPICS_FILE, "README.md"}
DEFAULT_TOPICS = (
    "cluster-hpc", "git-and-prs", "tools-and-sandbox", "chemistry-methods",
    "workflows", "delfin-development",
)
DEFAULT_REVIEW_DAYS = 180
DEFAULT_BUDGET_CHARS = 1600
_INDEX_HEADER = ("<!-- generated by `delfin-agent knowledge index` from the "
                 "entries; do not edit by hand -->")

#: A pointer to evidence, never the evidence itself: a test node, a
#: session id, a job id, a commit, a calc folder name, a PR or issue.
_EVIDENCE_RE = re.compile(
    r"^(?:test|session|job|commit|calc|pr|issue|doc|swarm|bench):"
    r"[^\s|]{1,160}$")
_DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
#: Pointers anyone can follow. A job, session, calc, swarm or bench id
#: names something on one machine: meaningless to a reader elsewhere and
#: a fact about the machine it came from.
PUBLIC_EVIDENCE_KINDS = ("test", "commit", "pr", "issue", "doc")
_SLUG_RE = re.compile(r"^[a-z0-9][a-z0-9-]{0,62}$")


@dataclass(frozen=True)
class Provenance:
    author: str
    date: str
    evidence: str

    def render(self) -> str:
        return f"{self.author} | {self.date} | {self.evidence}"


@dataclass
class Entry:
    slug: str
    title: str
    topic: str
    scope: str
    provenance: list = field(default_factory=list)
    review_by: str = ""
    situation: str = ""
    lesson: str = ""
    why: str = ""
    path: Optional[Path] = None
    layer: str = GLOBAL
    extra: str = ""          # body text outside the three labels

    @property
    def words(self) -> int:
        return len(f"{self.situation} {self.lesson} {self.why}".split())

    @property
    def text(self) -> str:
        """What the checks and the similarity read."""
        return (f"{self.title}\nSituation: {self.situation}\n"
                f"Lesson: {self.lesson}\nWhy: {self.why}")

    def expired(self, today: Optional[dt.date] = None) -> bool:
        try:
            return dt.date.fromisoformat(self.review_by) < (
                today or dt.date.today())
        except ValueError:
            return True


