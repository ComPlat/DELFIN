/**
 * Generate the TUI's protocol types from the one definition, the Python
 * module delfin/agent/service/protocol.py (its JSON Schema output).
 *
 *   bun scripts/gen-protocol.ts            write src/protocol/generated.ts
 *   bun scripts/gen-protocol.ts --check    exit 1 when the file is stale
 *
 * The Python that runs the module: $DELFIN_PYTHON, else `python3`. The test
 * test/protocol/generated.test.ts fails when the committed file and the
 * Python definition drift apart.
 */
import { resolve } from "node:path"

const TUI = resolve(import.meta.dir, "..")
const REPO = resolve(TUI, "..")
export const GENERATED = resolve(TUI, "src/protocol/generated.ts")

type Schema = {
  type?: string
  const?: string
  items?: Schema
  properties?: Record<string, Schema>
  required?: string[]
}

export function python(): string {
  return process.env.DELFIN_PYTHON || "python3"
}

export function loadSchema(): any {
  const run = Bun.spawnSync([python(), "-m", "delfin.agent.service.protocol"], {
    cwd: REPO,
    env: { ...process.env, PYTHONPATH: REPO },
    stdout: "pipe",
    stderr: "pipe",
  })
  if (run.exitCode !== 0) {
    throw new Error(`${python()} -m delfin.agent.service.protocol failed: ${run.stderr.toString()}`)
  }
  return JSON.parse(run.stdout.toString())
}

function tsType(s: Schema): string {
  if (s.const !== undefined) return JSON.stringify(s.const)
  switch (s.type) {
    case "string": return "string"
    case "integer":
    case "number": return "number"
    case "boolean": return "boolean"
    case "object": return "Record<string, unknown>"
    case "array": return `${tsType(s.items ?? {})}[]`
    default: return "unknown"
  }
}

function fields(s: Schema, indent = "  "): string {
  const required = new Set(s.required ?? [])
  return Object.entries(s.properties ?? {})
    // An optional field may also come as null: Python sends None for one
    // it has no value for (a session's title).
    .map(([name, field]) => required.has(name)
      ? `${indent}${JSON.stringify(name)}: ${tsType(field)}`
      : `${indent}${JSON.stringify(name)}?: ${tsType(field)} | null`)
    .join("\n")
}

function typeName(dotted: string, suffix: string): string {
  return dotted.split(/[.\-_]/).map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join("") + suffix
}

function map(name: string, entries: Record<string, Schema>, suffix: string): string[] {
  const out: string[] = []
  for (const [key, schema] of Object.entries(entries)) {
    const body = fields(schema)
    out.push(body ? `export interface ${typeName(key, suffix)} {\n${body}\n}`
                  : `export interface ${typeName(key, suffix)} {}`)
  }
  out.push(`export interface ${name} {\n${Object.keys(entries)
    .map((key) => `  ${JSON.stringify(key)}: ${typeName(key, suffix)}`).join("\n")}\n}`)
  return out
}

export function generate(schema: any): string {
  const parts: string[] = [
    "// Generated by tui/scripts/gen-protocol.ts from delfin/agent/service/protocol.py.",
    "// Do not edit: run `bun scripts/gen-protocol.ts` after changing the Python side.",
    "",
    `export const PROTOCOL_VERSION = ${Number(schema.protocolVersion)}`,
    "",
    `export const DURABLE_EVENTS: ReadonlySet<string> = new Set(${JSON.stringify(schema.durableEvents)})`,
    "",
    "export const ERRORS = {",
    ...Object.entries(schema.errors as Record<string, number>)
      .sort(([, a], [, b]) => b - a)
      .map(([name, code]) => `  ${name}: ${code},`),
    "} as const",
    "",
    ...map("WorkerRequests", schema.requests, "Params"),
    ...map("WorkerResults", schema.results, "Result"),
    ...map("WorkerEvents", schema.events, "Event"),
    ...map("ServiceRequests", schema.service.requests, "Params"),
    ...map("ServiceResults", schema.service.results, "Result"),
    ...map("ServiceEvents", schema.service.events, "Event"),
    `export interface SessionSummary {\n${fields(schema.service.sessionSummary)}\n}`,
    "",
    "/** Every event a window can receive: a session's own, and the service's. */",
    "export type AnyEvent = WorkerEvents[keyof WorkerEvents] | ServiceEvents[keyof ServiceEvents]",
    "",
    "/** Requests a window sends: the service's, and a session's (with sessionId). */",
    "export type Requests = ServiceRequests & {",
    "  [M in keyof WorkerRequests]: WorkerRequests[M] & { sessionId: string }",
    "}",
    "export type Results = ServiceResults & WorkerResults",
    "",
  ]
  return parts.join("\n")
}

if (import.meta.main) {
  const text = generate(loadSchema())
  if (process.argv.includes("--check")) {
    const current = await Bun.file(GENERATED).exists() ? await Bun.file(GENERATED).text() : ""
    if (current !== text) {
      console.error("src/protocol/generated.ts is stale: run `bun scripts/gen-protocol.ts`")
      process.exit(1)
    }
    console.log("src/protocol/generated.ts matches the Python definition")
  } else {
    await Bun.write(GENERATED, text)
    console.log(`wrote ${GENERATED}`)
  }
}
