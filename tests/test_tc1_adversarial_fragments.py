# SYNTHETIC test fixture written for DELFIN -- not ORCA output
"""TC1 reviewer adversarial tests: fragment recognition layer (nacht-s16).

Synthetic ensembles only (LICENSE_GUARD: no ORCA/GOAT fixtures in the
repo). Coordinates are generated by RDKit embedding at test time.

System: styrene C=Cc1ccccc1 -- the vinyl double bond merges with the
aromatic ring into ONE conjugated component (the ring carbon is a pi
node, the vinyl carbon too, joined by a single bond to a non-aromatic
atom), so a conjugated_backbone and exactly one backbone torsion point
(the ring-vinyl single bond) exist.

Attacks:
- torsion_points hardcodes status="recognized"
  (conformer_fragment_recognition.py:327-329) even when the bond graph
  is NOT stable across frames, while conjugated_pi / conjugated_backbone
  downgrade to "plausible" (:284, :296). The torsion bonds come from the
  first-frame graph only.
- perception failure mid-ensemble must yield status "unknown" with empty
  fragments, never a partial result presented as recognized.
"""
import numpy as np
import pytest
from rdkit import Chem
from rdkit.Chem import AllChem

from delfin.analysis_tools.conformer_fragment_recognition import (
    recognize_fragments,
)

SMILES = "C=Cc1ccccc1"


def _styrene_frames(stretch_double_bond_to=None):
    """Two styrene frames as XYZ text; optionally stretch the vinyl C=C."""
    mol = Chem.AddHs(Chem.MolFromSmiles(SMILES))
    AllChem.EmbedMolecule(mol, randomSeed=42)
    conf = mol.GetConformer()
    pos_a = np.array(conf.GetPositions())
    pos_b = pos_a.copy()
    if stretch_double_bond_to is not None:
        # vinyl double bond: between heavy atoms 0 and 1
        vec = pos_b[1] - pos_b[0]
        pos_b[1] = pos_b[0] + vec / np.linalg.norm(vec) * stretch_double_bond_to
    n = mol.GetNumAtoms()
    syms = [a.GetSymbol() for a in mol.GetAtoms()]
    lines = []
    for k, p in enumerate((pos_a, pos_b)):
        lines.append(str(n))
        lines.append(f"energy: -{k}.0")
        for s, (x, y, z) in zip(syms, p):
            lines.append(f"{s} {x:.5f} {y:.5f} {z:.5f}")
    return "\n".join(lines) + "\n", n


def _write_ensemble(tmp_path, text):
    path = tmp_path / "synthetic_crest.xyz"
    path.write_text(text)
    return path


def test_stable_ensemble_recognizes_ring_backbone_and_torsion(tmp_path):
    text, _n = _styrene_frames()
    path = _write_ensemble(tmp_path, text)
    res = recognize_fragments(path, charge=0)
    assert res["status"] == "recognized"
    assert res["graph_stable_across_frames"] is True
    kinds = [f["kind"] for f in res["fragments"]]
    assert "aromatic_ring" in kinds
    assert "conjugated_backbone" in kinds
    tors = next(f for f in res["fragments"]
                if f["kind"] == "torsion_points")
    assert tors["status"] == "recognized"
    # exactly the ring-vinyl single bond; ring bonds are excluded
    assert tors["bonds"] == [(7, 1)] or len(tors["bonds"]) == 1


def test_unstable_ensemble_must_not_claim_recognized_torsions(tmp_path):
    # stretch the vinyl C=C to 2.6 A: frame 1 perceives it as single,
    # frame 0 as double -> bond lists differ -> graph unstable. The
    # torsion bonds are taken from frame 0 only, so torsion_points must
    # NOT claim "recognized" (hardcoded at :327-329).
    text, _n = _styrene_frames(stretch_double_bond_to=2.6)
    path = _write_ensemble(tmp_path, text)
    res = recognize_fragments(path, charge=0)
    assert res["graph_stable_across_frames"] is False
    tors = next(f for f in res["fragments"]
                if f["kind"] == "torsion_points")
    assert tors["status"] != "recognized", (
        "torsion bonds are first-frame-only; with an unstable graph the "
        f"status must be plausible/unknown, got: {tors}")


def test_perception_failure_yields_unknown_not_partial(tmp_path):
    # collapse two vinyl atoms in frame 1 onto each other: perception
    # must fail and the WHOLE result must be unknown with no fragments
    text, n = _styrene_frames()
    lines = text.splitlines()
    count_positions = [i for i, l in enumerate(lines)
                       if l.strip() == str(n)]
    assert len(count_positions) == 2
    idx = count_positions[1]
    lines[idx + 1] = "C 0.00000 0.00000 0.00000"
    lines[idx + 2] = "C 0.00000 0.00000 0.00000"
    path = _write_ensemble(tmp_path, "\n".join(lines) + "\n")
    res = recognize_fragments(path, charge=0)
    assert res["status"] == "unknown"
    assert res["fragments"] == []
    assert res["reason"]
