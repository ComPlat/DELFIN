"""The Windows launcher's server side takes the install that install.sh set up.

Seen on an account that followed the old bwUniCluster guide (~/DELFIN/.venv)
and then ran install.sh (~/software/delfin/.venv): with no environment active
remote_bootstrap.sh stopped with "Multiple installations found"; with the
guide's `source ~/DELFIN/.venv/bin/activate` still in ~/.bashrc the login
shell had the OLD venv active and the launcher took it. install.sh records
its checkout in ~/.delfin_env.sh (export DELFIN_REPO=...), and that record
now decides. Runs the real script with bash, as the app does; no Windows.
"""

import os
import pathlib
import shlex
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1] / "tools" / "windows-launcher"


def _install(repo: pathlib.Path) -> pathlib.Path:
    for package in ("delfin", "delfin/agent", "delfin/dashboard"):
        (repo / package).mkdir(parents=True, exist_ok=True)
        (repo / package / "__init__.py").write_text("")
    (repo / "delfin/agent/where.py").write_text("")
    (repo / "delfin/dashboard/session.py").write_text("")
    (repo / "delfin/cli_voila.py").write_text("def main(argv):\n    print('--strict-port')\n")
    bin_dir = repo / ".venv" / "bin"
    bin_dir.mkdir(parents=True)
    (bin_dir / "python").symlink_to(sys.executable)
    (bin_dir / "activate").write_text(f"export VIRTUAL_ENV={shlex.quote(str(repo / '.venv'))}\n")
    return bin_dir / "python"


def _run(tmp_path, home, *, virtual_env=None):
    payload = tmp_path / "payload.py"
    payload.write_text('import sys; print("CHOSEN=" + sys.executable)\n')
    env = {k: v for k, v in os.environ.items() if k not in ("VIRTUAL_ENV", "CONDA_PREFIX", "DELFIN_REPO")}
    env.update(PATH="/usr/bin:/bin", HOME=str(home))
    if virtual_env:
        env["VIRTUAL_ENV"] = str(virtual_env)
    return subprocess.run(["bash", str(ROOT / "remote_bootstrap.sh"), "0", "", "", str(payload), "dashboard"],
                          env=env, text=True, capture_output=True, timeout=30)


def _two_installs(tmp_path, *, recorded=True):
    home = tmp_path / "home"
    old = _install(home / "DELFIN")
    new = _install(home / "software" / "delfin")
    if recorded:
        (home / ".delfin_env.sh").write_text(
            "# Auto-generated by DELFIN Runtime Setup\n"
            f"export DELFIN_REPO={shlex.quote(str(home / 'software' / 'delfin'))}\n")
    return home, old, new


def test_the_installers_checkout_is_taken_when_two_are_found(tmp_path):
    home, old, new = _two_installs(tmp_path)
    done = _run(tmp_path, home)
    assert done.returncode == 0, done.stderr
    assert f"CHOSEN={new}" in done.stdout
    assert "Multiple installations" not in done.stderr


def test_an_old_venv_active_in_the_login_shell_does_not_win(tmp_path):
    home, old, new = _two_installs(tmp_path)
    done = _run(tmp_path, home, virtual_env=old.parent.parent)
    assert done.returncode == 0, done.stderr
    assert f"CHOSEN={new}" in done.stdout
    assert str(old.parent.parent) in done.stdout + done.stderr, "the other environment is not named"


def test_without_a_record_the_choice_names_both_and_how_to_pick(tmp_path):
    home, old, new = _two_installs(tmp_path, recorded=False)
    done = _run(tmp_path, home)
    assert done.returncode == 1
    for repo in (home / "DELFIN", home / "software" / "delfin"):
        assert str(repo) in done.stderr, done.stderr
    assert "DELFIN location" in done.stderr
    assert "install.sh" in done.stderr
