"""The connectivity map on disk is the one the code produces.

``docs/WORKFLOW_CONNECTIVITY.md`` is generated by
``delfin.workflow_connectivity``, and this test is what keeps it honest: it
re-renders the map from the current ``delfin/`` source and compares, so a
renamed entry point, a new template key or a changed alias table cannot leave
the document claiming something the code no longer does.

The doc is also required to be complete in the direction that matters for the
package it serves: **every** template key appears in it.  A missing row is how
a key silently becomes undocumented, and it is the exact failure that had to be
found by hand here (``thermodynamics_mode`` / ``thermodynamics_reaction``,
reported as read by nothing because they are read under an alias).

These tests do not need ORCA, xTB or a network: they read ``delfin/`` and the
committed document.
"""

from __future__ import annotations

import re
from pathlib import Path

from delfin import workflow_connectivity as wc
from delfin.config import _canonicalize_control_key

REPO = Path(__file__).resolve().parent.parent
DOC = REPO / "docs" / "WORKFLOW_CONNECTIVITY.md"


def _document() -> str:
    assert DOC.is_file(), f"{DOC} is missing; run `python -m delfin.workflow_connectivity`"
    return DOC.read_text(encoding="utf-8")


def test_the_committed_map_is_what_the_code_renders():
    """Re-render from delfin/ and compare: the doc cannot drift from the code."""
    rendered = wc.render_connectivity_map()
    on_disk = _document()
    assert on_disk == rendered, (
        "docs/WORKFLOW_CONNECTIVITY.md is stale: regenerate it with "
        "`python -m delfin.workflow_connectivity`"
    )


def test_every_template_key_has_a_row_in_the_map():
    """No key of the CONTROL template may be missing from the table."""
    keys = wc.control_template_keys()
    assert len(keys) >= 180, f"the template shrank to {len(keys)} keys -- intended?"
    documented = set(re.findall(r"^\| `([^`]+)` \|", _document(), re.MULTILINE))
    missing = [k for k in keys if k not in documented]
    assert not missing, (
        f"{len(missing)} template key(s) are not documented in the map: {missing}"
    )


def test_a_key_read_only_under_an_alias_is_marked_as_such():
    """The two keys once reported as unused are shown with their alias.

    This is the assertion that would have failed on the literal-name scan: the
    value of ``thermodynamics_mode`` reaches a reader, but under the name
    ``stability_constant_mode``.
    """
    keys = wc.control_template_keys()
    doc = _document()
    alias_keys = [k for k in keys if _canonicalize_control_key(k) != k]
    assert "thermodynamics_mode" in alias_keys
    assert "thermodynamics_reaction" in alias_keys
    for key in ("thermodynamics_mode", "thermodynamics_reaction"):
        row = next((ln for ln in doc.splitlines()
                    if ln.startswith(f"| `{key}` |")), None)
        assert row is not None, f"{key} has no row in the map"
        canonical = _canonicalize_control_key(key)
        assert f"read as `{canonical}` (alias)" in row, (
            f"{key} must be documented as the alias of {canonical}; row was {row!r}"
        )


def test_a_target_shaped_key_is_explained_rather_than_called_unused():
    """`keyword:basename` is parsed by shape, and the map has to say so."""
    doc = _document()
    for key in ("keyword:basename", "additions:basename"):
        row = next((ln for ln in doc.splitlines() if ln.startswith(f"| `{key}` |")), None)
        assert row is not None, f"{key} has no row in the map"
    section = doc.split("## 6. Keys read without a literal occurrence", 1)[-1]
    assert "_OVERRIDE_KEY_RE" in section, (
        "the section must name the code that parses these keys, so a reader can check it"
    )


def test_every_module_in_the_table_still_has_its_entry_point():
    """The map names an entry point per module; each must exist in the code."""
    problems = wc.reachability_problems()
    assert not problems, "\n".join(problems)


def test_the_esd_entry_point_is_reached_from_the_pipeline_not_only_defined():
    """An import is not a caller: the pipeline must actually call ESD.

    ``delfin/esd_module.py`` defining ``execute_esd_jobs`` proves it exists.
    The question the map answers is whether a run reaches it, so the caller is
    asserted here rather than inferred from the import.
    """
    pipeline = (REPO / "delfin" / "workflows" / "pipeline.py").read_text(encoding="utf-8")
    assert "execute_esd_jobs" in pipeline, (
        "delfin/workflows/pipeline.py no longer imports ESD's entry point"
    )
    # The call, not the import line: the two are different ways of reaching it.
    assert re.search(r"result\s*=\s*execute_esd_module\(", pipeline), (
        "the pipeline imports execute_esd_jobs but no longer calls it"
    )


def test_the_map_names_the_workspace_rule_esd_depends_on():
    """The ESD entry records where its geometry comes from — the hand-over.

    The defect this package fixed was ESD looking for that geometry in the
    process directory.  The map states the rule, so the next reader does not
    have to rediscover it.
    """
    esd = next(m for m in wc.CONTROL_MODULES if m.name.startswith("ESD"))
    assert "workspace" in esd.handed, esd.handed
    assert "tests/test_a_control_run_writes_into_its_workspace.py" in esd.notes
